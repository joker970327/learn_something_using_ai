//! 第 1 课：Hello, Rust!
//!
//! 运行：cargo run --example 01_hello
//!
//! 要点：
//! - `fn main()` 是程序入口
//! - `println!` 末尾有 `!`，说明它是「宏」(macro)，不是普通函数
//! - 语句以分号 `;` 结尾
//! - `//` 是普通注释，`//!` 和 `///` 是文档注释

fn main() {
    println!("Hello, Rust!");

    // {} 是占位符，会被后面的参数依次替换
    let name = "小明";
    let age = 18;
    println!("我叫 {}，今年 {} 岁", name, age);

    // 也可以把变量名直接写进 {} 里（Rust 2021 起支持）
    println!("我叫 {name}，今年 {age} 岁");

    // {:?} 是「调试输出」，可以打印数组等复杂类型
    let nums = [1, 2, 3];
    println!("数组: {:?}", nums);

    // {:#?} 是美化版的调试输出（多行）
    println!("美化: {:#?}", nums);

    // 格式控制：保留两位小数、右对齐宽度 8
    let pi = 3.1415926;
    println!("pi ≈ {:.2}", pi);
    println!("[{:>8}]", "右对齐");

    // eprintln! 输出到标准错误
    eprintln!("这行输出到 stderr");
}

